// tools/embed-fontjs.mjs — inline the shared house script (https://adervec.github.io/font.js) into
// gym-tracker.html between the FONTJS markers, so the app stays one offline-capable file AND carries the
// whole current font.js (font, picker, About panel, what's new, crash notice, offline pill, zoom option,
// reduced motion, focus ring) instead of a hand-copied subset.
//
//   node tools/embed-fontjs.mjs              fetch the live file (deploy.yml runs this before publishing)
//   node tools/embed-fontjs.mjs <path>       use a local copy, e.g. ../CoworkSyncHub/font.js
//
// The embedded copy is committed, so tests and file:// use run against exactly what ships. If the fetch
// fails at deploy time, the committed copy is kept and a warning printed: a deploy never breaks over it.
import fs from 'node:fs';

const FILE = 'gym-tracker.html', URL_ = 'https://adervec.github.io/font.js';
const START = '<!-- FONTJS:START (generated by tools/embed-fontjs.mjs from adervec.github.io/font.js — do not edit by hand) -->';
const END = '<!-- FONTJS:END -->';

let src;
try {
  src = process.argv[2] ? fs.readFileSync(process.argv[2], 'utf8') : await (await fetch(URL_ + '?t=' + Date.now(), { cache: 'no-store' })).text();
} catch (e) {
  console.warn('embed-fontjs: could not read font.js (' + e.message + ') — keeping the committed copy');
  process.exit(0);
}
// Refuse anything that cannot run inlined: it must accept a base for its fonts and contain no closing tag.
if (!/window\.appFontBase/.test(src) || !/window\.appFont\s*=/.test(src)) { console.error('embed-fontjs: this font.js has no appFontBase hook or no appFont API — not embedding'); process.exit(1); }
if (/<\/script/i.test(src)) { console.error('embed-fontjs: font.js contains a closing script tag — it would end the inlined block early'); process.exit(1); }

const block = START + '\n'
  + '<script>window.appFontBase = \'fonts/\'; /* the woff2 files ship in ./fonts and are cached by sw.js */\n'
  + 'window.appUpdateNotice = false; /* the app shows its own "Update ready — tap to reload" toast (feat 465) */</script>\n'
  + '<script data-house="font.js">\n' + src.trim() + '\n</script>\n' + END;

let html = fs.readFileSync(FILE, 'utf8');
const a = html.indexOf(START), b = html.indexOf(END);
if (a < 0 || b < 0) { console.error('embed-fontjs: FONTJS markers not found in ' + FILE); process.exit(1); }
const before = html.slice(a, b + END.length);
if (before === block) { console.log('embed-fontjs: already current'); process.exit(0); }
html = html.slice(0, a) + block + html.slice(b + END.length);
fs.writeFileSync(FILE, html);
console.log('embed-fontjs: embedded font.js (' + (src.length / 1024).toFixed(1) + ' KB)');
